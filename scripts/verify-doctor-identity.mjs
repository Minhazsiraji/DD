/**
 * Doctor identity integrity — one BMDC registration number, one doctor.
 *
 * Found before the pilot: a second account was created through the real signup
 * flow using a BMDC number that already belonged to another doctor. Two
 * accounts holding one registration number is two accounts claiming to be the
 * same clinician, and that number prints on prescriptions.
 *
 * Executed as the real `authenticated` role inside a transaction that is ALWAYS
 * rolled back.
 *
 *   node --env-file=.env.local scripts/verify-doctor-identity.mjs
 */
import postgres from "postgres";
import crypto from "node:crypto";
import { BMDC_VECTORS } from "./bmdc-vectors.mjs";

const url = process.env.DIRECT_URL ?? process.env.DATABASE_URL;
if (!url) {
  console.error("DIRECT_URL or DATABASE_URL must be set.");
  process.exit(1);
}

const sql = postgres(url, {
  max: 1,
  prepare: false,
  onnotice: () => {},
  connection: { statement_timeout: "20000", lock_timeout: "10000" },
});
const failures = [];

function check(ok, label, detail = "") {
  console.log(`  ${ok ? "✓" : "✗"} ${label}${detail ? ` — ${detail}` : ""}`);
  if (!ok) failures.push(label);
}

async function refused(tx, fn) {
  try {
    await tx.savepoint(fn);
    return false;
  } catch {
    return true;
  }
}

/** Did it get through? Asked without letting it stand. */
async function accepted(tx, fn) {
  let got = false;
  try {
    await tx.savepoint(async (sp) => {
      await fn(sp);
      got = true;
      throw new Error("__undo__");
    });
  } catch (e) {
    if (e.message !== "__undo__") return false;
  }
  return got;
}

async function as(tx, uid, fn) {
  await tx`select set_config('request.jwt.claims', ${JSON.stringify({
    sub: uid,
    role: "authenticated",
  })}, true)`;
  await tx`set local role authenticated`;
  try {
    return await fn();
  } finally {
    await tx`reset role`;
  }
}

console.log("\nDoctor identity — one BMDC, one doctor");

// ---------------------------------------------------------------------------
console.log("\nThe constraint exists, and the key is not the caller's to supply");
{
  const [idx] = await sql`
    select indexdef from pg_indexes
    where schemaname = 'public' and indexname = 'doctor_profiles_bmdc_unique'`;
  check(Boolean(idx), "a unique index guards the normalised registration number");
  check(
    /UNIQUE/i.test(idx?.indexdef ?? "") && /bmdc_normalized/.test(idx?.indexdef ?? ""),
    "…on bmdc_normalized",
    idx?.indexdef ?? "missing",
  );
  check(
    /WHERE .*bmdc_normalized IS NOT NULL/i.test(idx?.indexdef ?? ""),
    "…partial, so doctors without a number do not compete",
  );

  const [col] = await sql`
    select is_generated, generation_expression
    from information_schema.columns
    where table_schema = 'public' and table_name = 'doctor_profiles'
      and column_name = 'bmdc_normalized'`;
  check(col?.is_generated === "ALWAYS", "the normalised value is GENERATED by the database");
  /**
   * The whole control. A normalised key a caller can write is not a key — an
   * honest number paired with a dishonest normalisation walks past the index.
   */
  check(
    await refused(sql, (t) =>
      t`insert into public.doctor_profiles (user_id, bmdc_normalized) values (null, 'X')`),
    "…and cannot be written directly, even by the table owner",
  );
}

/**
 * The DATABASE's folding, against the very vectors the TypeScript mirror is
 * tested with. If these two ever disagree, the app starts telling doctors a
 * number is free moments before the write refuses it.
 */
console.log("\nThe database folds exactly as the app expects");
{
  let drift = 0;
  for (const [input, expected] of BMDC_VECTORS) {
    const [row] = await sql`
      select nullif(upper(regexp_replace(coalesce(${input}::text, ''), '[^A-Za-z0-9]', '', 'g')), '')
             as norm`;
    if (row.norm !== expected) {
      drift++;
      console.log(`    ${JSON.stringify(input)} -> ${JSON.stringify(row.norm)}, expected ${JSON.stringify(expected)}`);
    }
  }
  check(drift === 0, `all ${BMDC_VECTORS.length} normalisation vectors agree with the app`);
}

const uidA = crypto.randomUUID();
const uidB = crypto.randomUUID();
const uidC = crypto.randomUUID();

try {
  await sql.begin(async (tx) => {
    for (const uid of [uidA, uidB, uidC]) {
      await tx`insert into auth.users (id, email, aud, role)
               values (${uid}, ${uid + "@qa.invalid"}, 'authenticated', 'authenticated')`;
      await tx`insert into public.profiles (id, full_name) values (${uid}, 'QA Doctor')`;
    }

    /**
     * A number that cannot collide with the real database.
     *
     * The first draft used a literal BMDC number and aborted the whole
     * transaction on setup, because a genuine account already holds it — which
     * is a fair demonstration that the constraint works, and a useless test.
     */
    const SUFFIX = crypto.randomBytes(4).toString("hex").toUpperCase();
    const BMDC = `QA${SUFFIX}Z`;
    const lower = BMDC.toLowerCase();
    await tx`insert into public.doctor_profiles (user_id, bmdc_registration_no)
             values (${uidA}, ${BMDC})`;

    // ---- 1. the exact duplicate --------------------------------------------
    console.log("\n1–3. A second doctor cannot take the same number");
    check(
      await refused(tx, (t) =>
        t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
          values (${uidB}, ${BMDC})`),
      "the SAME number is refused",
      BMDC,
    );

    // ---- 2. case variants ---------------------------------------------------
    for (const variant of [lower, `${BMDC.slice(0,4).toLowerCase()}${BMDC.slice(4)}`, `${BMDC.slice(0,-1)}${BMDC.slice(-1).toLowerCase()}`]) {
      check(
        await refused(tx, (t) =>
          t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
            values (${uidB}, ${variant})`),
        `a case variant is refused`,
        variant,
      );
    }

    // ---- 3. whitespace and punctuation --------------------------------------
    for (const variant of [
      `  ${BMDC}  `,
      `${BMDC.slice(0,2)} ${BMDC.slice(2,-1)} ${BMDC.slice(-1)}`,
      `${BMDC.slice(0,2)}-${BMDC.slice(2,-1)}-${BMDC.slice(-1)}`,
      `${BMDC.slice(0,2)}.${BMDC.slice(2,-1)}.${BMDC.slice(-1)}`,
      `${lower.slice(0,2)} - ${lower.slice(2,-1)} ${lower.slice(-1)}`,
    ]) {
      check(
        await refused(tx, (t) =>
          t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
            values (${uidB}, ${variant})`),
        `a formatting variant is refused`,
        JSON.stringify(variant),
      );
    }

    // ---- 4. a genuinely different number ------------------------------------
    console.log("\n4. A different doctor is still welcome");
    check(
      await accepted(tx, (t) =>
        t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
          values (${uidB}, ${BMDC.slice(0,-1) + "Y"})`),
      "a different registration number is accepted",
    );
    check(
      await accepted(tx, (t) =>
        t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
          values (${uidB}, null)`),
      "…as is a doctor who has not entered one yet",
    );
    check(
      await accepted(tx, (t) =>
        t`insert into public.doctor_profiles (user_id, bmdc_registration_no) values (${uidB}, '')`),
      "…and blank folds to nothing rather than colliding",
    );
    // Two blanks must coexist — the partial index is what allows it.
    check(
      await accepted(tx, async (t) => {
        await t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
                values (${uidB}, '')`;
        await t`insert into public.doctor_profiles (user_id, bmdc_registration_no)
                values (${uidC}, '   ')`;
      }),
      "…and two doctors without a number coexist",
    );

    // ---- 7. an UPDATE cannot collide either ---------------------------------
    console.log("\n7. Editing into someone else's number is refused too");
    await tx`insert into public.doctor_profiles (user_id, bmdc_registration_no)
             values (${uidB}, ${"QAOTHER" + SUFFIX})`;
    check(
      await refused(tx, (t) =>
        t`update public.doctor_profiles set bmdc_registration_no = ${lower.slice(0,2) + " " + lower.slice(2,-1) + " " + lower.slice(-1)}
           where user_id = ${uidB}`),
      "a doctor cannot EDIT their number into another doctor's",
    );
    check(
      await accepted(tx, (t) =>
        t`update public.doctor_profiles set bmdc_registration_no = ${"QA-OTHER-" + SUFFIX + "  "}
           where user_id = ${uidB}`),
      "…while re-saving their own, reformatted, is fine",
    );

    // ---- the display value is preserved -------------------------------------
    console.log("\nThe number a doctor typed is the number that prints");
    {
      const [row] = await tx`
        select bmdc_registration_no as stored, bmdc_normalized as norm
        from public.doctor_profiles where user_id = ${uidA}`;
      check(row.stored === BMDC, "the stored value is exactly as entered", row.stored);
      check(row.norm === BMDC.toUpperCase(), "…and the identity value is folded", row.norm);
    }

    // ---- 8. a refused signup leaves nothing behind ---------------------------
    console.log("\n8. A refused signup leaves no half-built practice");
    {
      const before = await tx`
        select
          (select count(*)::int from public.practice_locations)        as locations,
          (select count(*)::int from public.practice_location_members) as members,
          (select count(*)::int from public.doctor_profiles)           as doctors`;

      const denied = await refused(tx, (t) =>
        as(t, uidC, () =>
          t`select public.complete_onboarding(
              ${"Dr Duplicate"}, ${"MBBS"}, ${"Medicine"}, ${lower.slice(0,2) + " " + lower.slice(2,-1) + "-" + BMDC.slice(-1)}, ${"DD"},
              ${"Duplicate Chamber"}, ${"PERSONAL_CHAMBER"}::public.location_type,
              ${"1 Test Road"}, ${"Dhaka"}, ${"01700000000"})`),
      );
      check(denied, "onboarding with a taken number is refused");

      const after = await tx`
        select
          (select count(*)::int from public.practice_locations)        as locations,
          (select count(*)::int from public.practice_location_members) as members,
          (select count(*)::int from public.doctor_profiles)           as doctors`;
      check(
        after[0].locations === before[0].locations,
        "…and no practice location was left behind",
        `${before[0].locations} -> ${after[0].locations}`,
      );
      check(
        after[0].members === before[0].members && after[0].doctors === before[0].doctors,
        "…nor a membership or a doctor record",
      );
    }

    // ---- 9. onboarding with a FREE number still works ------------------------
    console.log("\n9. A legitimate signup is unaffected");
    {
      const ok = await accepted(tx, (t) =>
        as(t, uidC, () =>
          t`select public.complete_onboarding(
              ${"Dr Fresh"}, ${"MBBS"}, ${"Medicine"}, ${"QAFRESH" + SUFFIX}, ${"DF"},
              ${"Fresh Chamber"}, ${"PERSONAL_CHAMBER"}::public.location_type,
              ${"2 Test Road"}, ${"Dhaka"}, ${"01700000000"})`),
      );
      check(ok, "onboarding with an unused number succeeds");
    }

    // ---- 5. the clinic phone is NOT an identity ------------------------------
    console.log("\n5. Two chambers may share a phone — that is normal");
    {
      const shared = "01404385102";
      const [l1] = await tx`
        insert into public.practice_locations (name, type, phone, created_by)
        values ('Clinic One', 'CLINIC', ${shared}, ${uidA}) returning id`;
      check(
        await accepted(tx, (t) =>
          t`insert into public.practice_locations (name, type, phone, created_by)
            values ('Clinic Two', 'CLINIC', ${shared}, ${uidB})`),
        "a second location with the same clinic phone is accepted",
        shared,
      );
      check(Boolean(l1.id), "…and the first is untouched");

      const phoneIdx = await tx`
        select indexname from pg_indexes
        where schemaname = 'public' and tablename = 'practice_locations'
          and indexdef ilike '%unique%' and indexdef ilike '%phone%'`;
      check(
        phoneIdx.length === 0,
        "no unique index makes a clinic phone an identity",
        phoneIdx.map((i) => i.indexname).join(", "),
      );
    }

    // ---- 6. one email, one account ------------------------------------------
    console.log("\n6. Authentication identity stays Supabase's");
    {
      const [existing] = await tx`select email from auth.users where id = ${uidA}`;
      check(
        await refused(tx, (t) =>
          t`insert into auth.users (id, email, aud, role)
            values (${crypto.randomUUID()}, ${existing.email}, 'authenticated', 'authenticated')`),
        "a second account cannot take the same email address",
        existing.email,
      );
    }

    throw new Error("__rollback__");
  });
} catch (e) {
  if (e.message !== "__rollback__") {
    console.error("\nverification aborted:", e.message);
    failures.push("run aborted");
  }
}

// ---------------------------------------------------------------------------
// The live database must actually satisfy the constraint.
// ---------------------------------------------------------------------------
console.log("\nThe existing data holds");
{
  const dupes = await sql`
    select bmdc_normalized, count(*)::int as n
    from public.doctor_profiles
    where bmdc_normalized is not null
    group by bmdc_normalized having count(*) > 1`;
  check(
    dupes.length === 0,
    "no two doctor identities share a registration number",
    dupes.map((d) => `${d.bmdc_normalized} x${d.n}`).join(", "),
  );
}

console.log(
  failures.length === 0
    ? "\nDoctor identity: all checks passed.\n"
    : `\n${failures.length} FAILED:\n  ${failures.join("\n  ")}\n`,
);
await sql.end();
process.exit(failures.length === 0 ? 0 : 1);
